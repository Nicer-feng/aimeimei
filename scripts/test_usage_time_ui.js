const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const base=process.env.USAGE_TEST_URL;
  assert.match(base||'',/^http:\/\/127\.0\.0\.1:\d+$/);
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try {
    const context=await browser.newContext({viewport:{width:1440,height:960}});
    await context.addCookies([{name:'ap_session',value:'reader-a',url:base}]);
    const page=await context.newPage(),errors=[];
    page.on('pageerror',e=>errors.push(String(e)));
    const config=page.waitForResponse(r=>r.url().endsWith('/api/usage-time/config'));
    await page.goto(base);await config;await page.waitForFunction(()=>state.authed);
    await page.locator('#prompt').click();await page.waitForTimeout(5500);
    const stats=()=>page.evaluate(async()=>{await MeimeiUsage.flush();return(await(await fetch('/api/usage-time/self')).json()).summary;});
    const work=await stats();assert.ok(work.work_ms>=4000,JSON.stringify(work));
    const other=await context.newPage();await other.goto('about:blank');
    // Headless Chrome treats all tabs as focused; exercise the browser blur handler explicitly.
    await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
    await page.waitForTimeout(6000);
    const background=await stats();assert.ok(background.total_ms-work.total_ms<1500,JSON.stringify({work,background}));
    await other.close();await page.bringToFront();
    await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
    await page.evaluate(async()=>{
      await fetch('/api/reading/books?filename=usage-test.txt',{method:'POST',body:'阅读用测试文本。\n'.repeat(400)});
    });
    await page.locator('#readerToggle').click();await page.waitForFunction(()=>MeimeiReader.active && document.querySelector('#readerPages .reader-text'));
    await page.waitForTimeout(5500);
    const reading=await stats();assert.ok(reading.reading_ms>=4000,JSON.stringify(reading));
    await page.evaluate(()=>openTokenActivity());
    await page.locator('[data-activity-tab="usage"]').click();
    await page.waitForFunction(()=>document.querySelector('#personalUsageTime .usage-time-metric'));
    assert.equal(await page.locator('#tokenActivityContent').isVisible(),false);
    const modalStart=await stats();await page.waitForTimeout(1200);const modalEnd=await stats();
    assert.equal(modalEnd.reading_ms,modalStart.reading_ms);
    assert.ok(modalEnd.work_ms>modalStart.work_ms);
    await page.screenshot({path:'/private/tmp/usage-time-personal.png'});
    await page.setViewportSize({width:390,height:844});await page.waitForTimeout(200);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.screenshot({path:'/private/tmp/usage-time-mobile.png'});
    await page.locator('[data-activity-tab="tokens"]').click();
    assert.equal(await page.locator('#tokenActivityContent').isVisible(),true);
    assert.equal(await page.locator('#personalUsageTime').isVisible(),false);
    const admin=await browser.newContext({viewport:{width:1440,height:1000}});
    await admin.addCookies([{name:'ap_session',value:'usage-admin',url:base}]);
    const ap=await admin.newPage();ap.on('pageerror',e=>errors.push(String(e)));
    let details=0;
    ap.on('request',r=>{if(r.url().includes('/api/usage-time/admin/user?'))details++;});
    await ap.goto(base);await ap.waitForFunction(()=>state.authed);
    await ap.evaluate(()=>{openSettings();switchAdminSection('usage');});
    await ap.locator('#adminUsageTime .usage-time-account').first().waitFor();
    assert.equal(details,0);
    await ap.locator('#adminUsageTime .usage-time-account button').first().click();
    await ap.locator('#adminUsageTime .usage-time-detail table').waitFor();assert.equal(details,1);
    await ap.screenshot({path:'/private/tmp/usage-time-admin.png'});
    await ap.locator('#adminUsageTime input[placeholder="用户名或昵称"]').fill('no-such-user');
    await ap.waitForFunction(()=>document.querySelector('#adminUsageTime .usage-time-results').textContent.includes('没有找到'));
    await ap.evaluate(()=>document.documentElement.dataset.theme='dark');
    await ap.screenshot({path:'/private/tmp/usage-time-dark.png'});
    await ap.route('**/api/usage-time/admin?**',r=>r.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'测试暂时不可用'})}));
    await ap.locator('#adminUsageTime .usage-time-filter > button').click();
    await ap.waitForFunction(()=>document.querySelector('#adminUsageTime .usage-time-status').textContent.includes('测试暂时不可用'));
    await ap.unroute('**/api/usage-time/admin?**');
    await ap.locator('#adminUsageTime .usage-time-filter > button').click();
    await ap.waitForFunction(()=>document.querySelector('#adminUsageTime .usage-time-status').textContent==='');
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({work,background,reading,detailsOnDemand:details,errors}));
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
