const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const base = process.env.READER_TEST_URL;
  assert.match(base || '', /^http:\/\/127\.0\.0\.1:\d+$/);
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await context.addCookies([{ name: 'ap_session', value: 'reader-a', url: base }]);
    const page = await context.newPage(), errors = [];
    page.on('pageerror', e => errors.push(String(e)));
    await page.goto(base); await page.waitForFunction(() => state.authed);
    await page.evaluate(() => openSettings());
    await page.locator('[data-admin-section="logins"]').click();
    await page.waitForFunction(() => document.querySelectorAll('#loginHistoryRows tr').length === 50);
    assert.equal(await page.locator('[data-admin-page="logins"]').evaluate(e => !!e.parentElement.closest('[data-admin-page]')), false);
    await page.locator('#loginHistoryNext').click();
    await page.waitForFunction(() => document.querySelectorAll('#loginHistoryRows tr').length === 8);
    await page.locator('#loginHistoryPrev').click();
    await page.waitForFunction(() => document.querySelectorAll('#loginHistoryRows tr').length === 50);
    await page.locator('.admin-control').filter({ has: page.locator('#loginHistoryPlatform') }).locator('.admin-control-trigger').click();
    await page.getByRole('option', { name: '安卓 App', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('#loginHistoryRows tr').length === 1);
    assert.match(await page.locator('#loginHistoryRows').innerText(), /internal-model/);
    await page.waitForTimeout(350);
    await page.screenshot({ path: '/private/tmp/meimei-login-records-desktop.png' });
    await page.evaluate(() => switchAdminSection('accounts'));
    await page.waitForFunction(() => state.adminUsers?.some(u => u.id === 'reader-b'));
    const row = page.locator('#accountList .model-row').filter({ hasText: 'reader-b' });
    await row.getByRole('button', { name: '设备记录', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#loginHistoryUser').value === 'reader-b' && document.querySelectorAll('#loginHistoryRows tr').length > 0);
    assert.match(await page.locator('#loginHistoryRows').innerText(), /推送能力：未接入/);
    assert.match(await page.locator('#loginHistoryRows').innerText(), /会话有效/);
    assert.doesNotMatch(await page.locator('#loginHistoryRows').innerText(), /手机已收到|实时在线/);
    await page.waitForTimeout(350);
    await page.screenshot({ path: '/private/tmp/meimei-client-devices-desktop.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => { closeSidebar(); openSettings(); switchAdminSection('logins'); });
    await page.waitForFunction(() => document.querySelectorAll('#loginHistoryRows tr').length > 0);
    await page.waitForTimeout(400);
    await page.screenshot({ path: '/private/tmp/meimei-login-records-mobile.png' });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.evaluate(() => applyCurrentUser(null));
    assert.equal(await page.locator('#loginHistoryRows tr').count(), 0);
    const ordinary = await browser.newContext();
    await ordinary.addCookies([{ name: 'ap_session', value: 'reader-b', url: base }]);
    const result = await ordinary.request.get(base + '/api/admin/login-records');
    assert.equal(result.status(), 401);
    assert.deepEqual(errors, []);
    console.log('登录记录分页/筛选、账号设备入口、手机布局和界面清理通过');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
